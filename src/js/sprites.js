  function render(key, opts = {}) {
    const ck = key + JSON.stringify(opts);
    if (cache.has(ck)) return cache.get(ck);
    const spr = D[key];
    if (!spr) return '';
    const pal = Object.assign({}, spr.pal, opts.pal || {});
    const c = document.createElement('canvas');
    c.width = 16; c.height = 16;
    const g = c.getContext('2d');
    spr.g.forEach((row, y) => {
      for (let x = 0; x < 16; x++) {
        const ch = row[x];
        if (ch === '.' || !pal[ch]) continue;
        g.fillStyle = pal[ch];
        g.fillRect(x, y, 1, 1);
      }
    });
    for (const [x, y, col] of opts.overlay || []) { g.fillStyle = col; g.fillRect(x, y, 1, 1); }
    let url = '';
    try { url = c.toDataURL('image/png'); } catch (e) { url = ''; }
    cache.set(ck, url);
    return url;
  }

